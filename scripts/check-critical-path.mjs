import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const CRITICAL_PATHS = Object.freeze([
  'src/ingestion/Cxp13Runtime.js',
  'src/ingestion/IngestionPipelineController.js',
  'src/ingestion/InputAdapter.js',
  'src/repository/RawDataRepository.js',
  'src/repository/StagingRepository.js',
  'src/services/CommitService.js',
  'src/services/RollbackService.js',
]);

const STAMP_RELATIVE_PATH = 'src/release/Cxp14CriticalPathStamp.js';
const CONTRACT_VERSION = 1;
const SINGLE_CELL_CALL = /\.(?:getValue|setValue)\s*\(/g;
const ROW_INDEXED_RANGE = /\.getRange\s*\(\s*(?:row|rowIndex|recordIndex|index)\b/g;

export function findCriticalPathViolations(files) {
  const violations = [];

  for (const file of files) {
    const normalized = file.path.replaceAll('\\', '/');
    if (!CRITICAL_PATHS.includes(normalized)) continue;

    for (const match of file.content.matchAll(SINGLE_CELL_CALL)) {
      violations.push({ index: match.index, path: normalized, rule: 'single-cell-spreadsheet-call' });
    }
    for (const match of file.content.matchAll(ROW_INDEXED_RANGE)) {
      violations.push({ index: match.index, path: normalized, rule: 'row-indexed-range-call' });
    }
  }

  return violations;
}

export function hashContent(content) {
  return createHash('sha256').update(content, 'utf8').digest('hex');
}

export function buildStamp(files, violations = findCriticalPathViolations(files)) {
  const hashes = {};
  for (const file of files) {
    const normalized = file.path.replaceAll('\\', '/');
    if (!CRITICAL_PATHS.includes(normalized)) continue;
    hashes[normalized] = hashContent(file.content);
  }
  const pass = violations.length === 0 && CRITICAL_PATHS.every((item) => typeof hashes[item] === 'string');
  return Object.freeze({
    contractVersion: CONTRACT_VERSION,
    hashes: Object.freeze(hashes),
    pass,
    version: 1,
  });
}

export function renderStampModule(stamp) {
  const hashes = JSON.stringify(stamp.hashes, Object.keys(stamp.hashes).sort(), 2)
    .replace(/\n/g, '\n    ');
  return [
    '/** Generated by scripts/check-critical-path.mjs. Do not edit by hand. */',
    'var Cxp14CriticalPathStamp = (function () {',
    "  'use strict';",
    '  return Object.freeze({',
    `    contractVersion: ${stamp.contractVersion},`,
    `    hashes: Object.freeze(${hashes}),`,
    `    pass: ${stamp.pass === true},`,
    '    version: 1,',
    '  });',
    '})();',
    '',
    'if (typeof module !== \'undefined\' && module.exports) module.exports = Cxp14CriticalPathStamp;',
    '',
  ].join('\n');
}

export function stampMatches(expected, actual) {
  if (!expected || !actual) return false;
  if (expected.pass !== true || actual.pass !== true) return false;
  if (expected.contractVersion !== actual.contractVersion) return false;
  const expectedKeys = Object.keys(expected.hashes || {}).sort();
  const actualKeys = Object.keys(actual.hashes || {}).sort();
  if (expectedKeys.join('|') !== actualKeys.join('|')) return false;
  return expectedKeys.every((key) => expected.hashes[key] === actual.hashes[key]);
}

async function collect(projectRoot) {
  const files = [];
  for (const relativePath of CRITICAL_PATHS) {
    files.push({
      path: relativePath,
      content: await readFile(path.join(projectRoot, relativePath), 'utf8'),
    });
  }
  return files;
}

async function readExistingStamp(projectRoot) {
  const stampPath = path.join(projectRoot, STAMP_RELATIVE_PATH);
  try {
    const source = await readFile(stampPath, 'utf8');
    const hashesMatch = source.match(/hashes:\s*Object\.freeze\((\[[\s\S]*?\]|\{[\s\S]*?\})\)/);
    const pass = /pass:\s*true/.test(source);
    const contract = source.match(/contractVersion:\s*(\d+)/);
    const hashes = hashesMatch ? JSON.parse(hashesMatch[1]) : null;
    return { contractVersion: contract ? Number(contract[1]) : null, hashes, pass };
  } catch (_error) {
    return null;
  }
}

async function main() {
  const projectRoot = process.cwd();
  const writeRequested = process.argv.includes('--write');
  const files = await collect(projectRoot);
  const violations = findCriticalPathViolations(files);
  if (violations.length) {
    for (const violation of violations) {
      console.error(`${violation.path}: blocked by ${violation.rule}`);
    }
    process.exitCode = 1;
    return;
  }
  const stamp = buildStamp(files, violations);
  if (writeRequested) {
    await writeFile(path.join(projectRoot, STAMP_RELATIVE_PATH), renderStampModule(stamp), 'utf8');
    console.log(`Critical-path stamp written (${files.length} files).`);
    return;
  }
  const existing = await readExistingStamp(projectRoot);
  if (!stampMatches(stamp, existing)) {
    console.error('CXP-14 critical-path stamp is missing or stale. Run node scripts/check-critical-path.mjs --write');
    process.exitCode = 1;
    return;
  }
  console.log(`Critical-path bulk-call guard passed (${files.length} files scanned).`);
}

const invokedPath = process.argv[1] ? path.resolve(process.argv[1]) : '';
if (invokedPath === fileURLToPath(import.meta.url)) {
  main().catch((error) => {
    console.error(error.stack || error.message);
    process.exitCode = 1;
  });
}
